"""Regenerate the two aggregate copies of the workstream ISSUES files, from each
Research/<Workstream>/ISSUES.md (the single source):

  - the per-workstream issues section of Research/research_board.md, and
  - Research/ISSUES.md, all workstreams in one file.

    python3 tools/build_board.py          # rewrite both in place
    python3 tools/build_board.py --check  # exit 1 if either is stale

The board section lives between the BEGIN/END markers below; everything else in
the board is hand-maintained. Headings inside each ISSUES.md are demoted two
levels so they nest under the workstream heading, relative links are
rebased from Research/<Workstream>/ to Research/, and issue IDs become links
to the defining ISSUES.md (tools/link_issue_refs.py), including the
references a workstream file makes to its own IDs.
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'python'))
import evoca_paths  # noqa: E402
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import link_issue_refs  # noqa: E402

BOARD = os.path.join(evoca_paths.RESEARCH, 'research_board.md')
ISSUES = os.path.join(evoca_paths.RESEARCH, 'ISSUES.md')
BEGIN = '<!-- BEGIN workstream-issues (generated by tools/build_board.py; edit Research/<WS>/ISSUES.md) -->'
END = '<!-- END workstream-issues -->'
LINK = re.compile(r'(\]\()([^)\s]+)(\))')


def rebase_links(line, ws):
    """A relative link written in Research/<ws>/ISSUES.md, re-aimed for a file in Research/."""
    def fix(m):
        target = m.group(2)
        if re.match(r'[a-z]+:|#|/', target):
            return m.group(0)
        return m.group(1) + os.path.normpath(os.path.join(ws, target)) + m.group(3)
    return LINK.sub(fix, line)


def render():
    """The per-workstream sections, shared by the board and Research/ISSUES.md."""
    parts = []
    for ws in evoca_paths.WORKSTREAMS:
        p = os.path.join(evoca_paths.RESEARCH, ws, 'ISSUES.md')
        parts.append(f'### {ws}')
        parts.append('')
        if not os.path.exists(p):
            parts += ['_No ISSUES.md yet._', '']
            continue
        body = open(p).read().strip().splitlines()
        if body and body[0].startswith('# '):      # drop the file's own title
            body = body[1:]
        body = [re.sub(r'^(#{2,4}) ', lambda m: '#' * (len(m.group(1)) + 2) + ' ', ln) for ln in body]
        body = [rebase_links(ln, ws) for ln in body]
        parts += [f'Source: [`{ws}/ISSUES.md`]({ws}/ISSUES.md)', ''] + body + ['']
    # both outputs live in Research/, so one linking pass serves both
    text, _ = link_issue_refs.link_text('\n'.join(parts), 'Research/ISSUES.md', link_issue_refs.definitions())
    return text.split('\n')


def render_board_section(sections):
    return '\n'.join([BEGIN, ''] + sections + [END])


def render_issues(sections):
    head = ['# EvoCA research: all open issues',
            '',
            '_Generated by `tools/build_board.py` from each `Research/<Workstream>/ISSUES.md`; '
            'edit those files, not this one._',
            '',
            'Workstreams: ' + ' · '.join(f'[{ws}](#{ws.lower()})' for ws in evoca_paths.WORKSTREAMS),
            '']
    # one level up: the workstream is a top-level section here
    body = [ln[1:] if ln.startswith('##') else ln for ln in sections]
    return '\n'.join(head + body).rstrip() + '\n'


def main():
    sections = render()
    board = open(BOARD).read()
    if BEGIN not in board or END not in board:
        sys.exit(f'markers not found in {BOARD}')
    new_board = board[:board.index(BEGIN)] + render_board_section(sections) + board[board.index(END) + len(END):]
    old_issues = open(ISSUES).read() if os.path.exists(ISSUES) else ''
    new_issues = render_issues(sections)
    if '--check' in sys.argv:
        sys.exit(0 if (new_board == board and new_issues == old_issues) else 1)
    for path, old, new in ((BOARD, board, new_board), (ISSUES, old_issues, new_issues)):
        name = os.path.relpath(path, evoca_paths.REPO_ROOT)
        if new != old:
            open(path, 'w').write(new)
            print(f'{name} updated')
        else:
            print(f'{name} up to date')


if __name__ == '__main__':
    main()
