"""Regenerate the per-workstream issues section of Research/research_board.md
from each Research/<Workstream>/ISSUES.md (the single source).

    python3 tools/build_board.py          # rewrite the section in place
    python3 tools/build_board.py --check  # exit 1 if the board is stale

The section lives between the BEGIN/END markers below; everything else in
the board is hand-maintained. Headings inside each ISSUES.md are demoted
two levels so they nest under the workstream heading.
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'python'))
import evoca_paths  # noqa: E402

BOARD = os.path.join(evoca_paths.RESEARCH, 'research_board.md')
BEGIN = '<!-- BEGIN workstream-issues (generated by tools/build_board.py; edit Research/<WS>/ISSUES.md) -->'
END = '<!-- END workstream-issues -->'


def render():
    parts = [BEGIN, '']
    for ws in evoca_paths.WORKSTREAMS:
        p = os.path.join(evoca_paths.RESEARCH, ws, 'ISSUES.md')
        parts.append(f'### {ws}')
        parts.append('')
        if not os.path.exists(p):
            parts += ['_No ISSUES.md yet._', '']
            continue
        body = open(p).read().strip().splitlines()
        if body and body[0].startswith('# '):      # drop the file's own title
            body = body[1:]
        body = [re.sub(r'^(#{2,4}) ', lambda m: '#' * (len(m.group(1)) + 2) + ' ', ln) for ln in body]
        parts += [f'Source: [`{ws}/ISSUES.md`]({ws}/ISSUES.md)', ''] + body + ['']
    parts.append(END)
    return '\n'.join(parts)


def main():
    board = open(BOARD).read()
    if BEGIN not in board or END not in board:
        sys.exit(f'markers not found in {BOARD}')
    new = board[:board.index(BEGIN)] + render() + board[board.index(END) + len(END):]
    if '--check' in sys.argv:
        sys.exit(0 if new == board else 1)
    if new != board:
        open(BOARD, 'w').write(new)
        print('board updated')
    else:
        print('board up to date')


if __name__ == '__main__':
    main()
